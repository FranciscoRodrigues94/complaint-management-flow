-- Eigenständige Demo-Datenbank. Keine geschäftlichen Kundendaten oder internen Prozesskennzeichen.
CREATE TABLE IF NOT EXISTS complaints (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reference VARCHAR(32) NOT NULL UNIQUE,
    title VARCHAR(160) NOT NULL CHECK (length(trim(title)) >= 3),
    customer VARCHAR(120) NOT NULL,
    item_code VARCHAR(60) NOT NULL,
    category VARCHAR(40) NOT NULL CHECK (category IN ('Visual defect', 'Dimensional', 'Packaging', 'Assembly', 'Other')),
    severity VARCHAR(12) NOT NULL CHECK (severity IN ('Low', 'Medium', 'High')),
    status VARCHAR(24) NOT NULL DEFAULT 'Open' CHECK (status IN ('Open', 'In Progress', 'Pending Verification', 'Closed')),
    description TEXT NOT NULL,
    reporter VARCHAR(100) NOT NULL,
    assigned_to VARCHAR(100) NOT NULL,
    affected_quantity INTEGER NOT NULL CHECK (affected_quantity >= 1),
    rejected_quantity INTEGER NOT NULL CHECK (rejected_quantity >= 0 AND rejected_quantity <= affected_quantity),
    containment_action TEXT NOT NULL DEFAULT '',
    root_cause TEXT NOT NULL DEFAULT '',
    verification_result VARCHAR(20) NOT NULL DEFAULT 'Not reviewed' CHECK (verification_result IN ('Not reviewed', 'Effective', 'Ineffective')),
    verification_notes TEXT NOT NULL DEFAULT '',
    verified_by VARCHAR(100) NOT NULL DEFAULT '',
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_complaints_status ON complaints(status);
CREATE INDEX IF NOT EXISTS idx_complaints_created_at ON complaints(created_at DESC);
CREATE TABLE IF NOT EXISTS corrective_actions (
    id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    complaint_id BIGINT NOT NULL REFERENCES complaints(id) ON DELETE RESTRICT,
    title VARCHAR(200) NOT NULL,
    owner VARCHAR(100) NOT NULL,
    due_date DATE NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'Open' CHECK (status IN ('Open', 'In Progress', 'Completed')),
    completed_at TIMESTAMPTZ
);
CREATE INDEX IF NOT EXISTS idx_corrective_actions_complaint ON corrective_actions(complaint_id);
CREATE TABLE IF NOT EXISTS complaint_events (
    id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    complaint_id BIGINT NOT NULL REFERENCES complaints(id) ON DELETE RESTRICT,
    event_type VARCHAR(32) NOT NULL,
    message VARCHAR(600) NOT NULL,
    actor VARCHAR(100) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_complaint_events_complaint ON complaint_events(complaint_id, created_at DESC);
